/** Compile the upstream Tailwind theme once; deployment receives ordinary CSS. */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import tailwindcss from "../app/node_modules/@tailwindcss/vite/dist/index.mjs";
import { build } from "../app/node_modules/vite/dist/node/index.js";
import { katexWoff2Only } from "../app/vendor/build/katex-woff2-only.ts";

const here = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "../app/ui"
);
const result = await build({
  configFile: false,
  root: path.dirname(here),
  plugins: [tailwindcss(), katexWoff2Only()],
  build: {
    write: false,
    lib: {
      entry: path.join(here, "source.css"),
      formats: ["es"],
      fileName: () => "unused.js",
    },
    assetsInlineLimit: 10_000_000,
    cssCodeSplit: true,
    rollupOptions: { output: { assetFileNames: "styles.css" } },
  },
});
const outputs = (Array.isArray(result) ? result : [result]).flatMap(
  (item) => item.output
);
const css = outputs.find(
  (file) => file.type === "asset" && file.fileName.endsWith(".css")
);
if (!css) {
  throw new Error("The upstream stylesheet was not produced.");
}
// The host currently classifies esbuild CSS data: URLs as unresolved imports.
// A style text module preserves the exact self-contained CSS without routing
// those already-resolved fonts and SVGs through the file-loader validator.
fs.writeFileSync(
  path.join(here, "styles.ts"),
  `// Generated by scripts/build-css.mjs from upstream CSS.\nexport default ${JSON.stringify(css.source)};\n`
);
console.log(`Wrote ${css.source.length} bytes of self-contained CSS.`);
